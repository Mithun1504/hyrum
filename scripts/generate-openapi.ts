import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { astToString, default as openapiTS } from "openapi-typescript";
import { buildApp } from "../apps/control-plane/src/app";

const root = resolve(import.meta.dirname, "..");
const env = {
  NODE_ENV: "test" as const,
  LOG_LEVEL: "silent" as const,
  CONTROL_PLANE_HOST: "127.0.0.1",
  CONTROL_PLANE_PORT: 4000,
  WEB_URL: "http://localhost:3000",
  DATABASE_URL: "postgresql://localhost/hyrum_openapi",
  DATABASE_SSL: false,
  DATABASE_POOL_MAX: 1,
  OBJECT_STORAGE_ENDPOINT: "http://127.0.0.1:9000",
  OBJECT_STORAGE_REGION: "us-east-1",
  OBJECT_STORAGE_BUCKET: "hyrum-development",
  OBJECT_STORAGE_ACCESS_KEY_ID: "minioadmin",
  OBJECT_STORAGE_SECRET_ACCESS_KEY: "minioadmin",
  OBJECT_STORAGE_FORCE_PATH_STYLE: true,
  OBJECT_STORAGE_MAX_OBJECT_BYTES: 25 * 1024 * 1024,
  OBJECT_STORAGE_PRESIGN_MAX_SECONDS: 300,
  OBJECT_STORAGE_SERVER_SIDE_ENCRYPTION: "bucket" as const,
};

async function main() {
  const app = await buildApp({ env, includeDatabase: false });
  await app.ready();
  const document = app.swagger();
  await app.close();

  const openapiDirectory = resolve(root, "packages/api-client/openapi");
  await mkdir(openapiDirectory, { recursive: true });
  await writeFile(
    resolve(openapiDirectory, "control-plane.json"),
    `${JSON.stringify(document, null, 2)}\n`,
    "utf8",
  );
  const nodes = await openapiTS(document);
  await writeFile(
    resolve(root, "packages/api-client/src/generated.ts"),
    `/* Generated by scripts/generate-openapi.ts. Do not edit manually. */\n${astToString(nodes)}`,
    "utf8",
  );
}

main().catch((error: unknown) => {
  process.stderr.write(`${error instanceof Error ? error.stack : String(error)}\n`);
  process.exitCode = 1;
});
